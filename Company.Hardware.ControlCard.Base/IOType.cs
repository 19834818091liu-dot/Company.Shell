using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Company.Hardware.ControlCard.Base
{
    /// <summary>
    /// 位标志枚举
    /// </summary>
    [Flags]
    public enum IOType :uint
    {
        IO0 = 0x00000001, // 2^0 = 1
        IO1 = 0x00000002, // 2^1 = 2
        IO2 = 0x00000004, // 2^2 = 4
        IO3 = 0x00000008, // 2^3 = 8
        IO4 = 0x00000010, // 2^4 = 16
        IO5 = 0x00000020, // 2^5 = 32
        IO6 = 0x00000040, // 2^6 = 64
        IO7 = 0x00000080, // 2^7 = 128
        IO8 = 0x00000100, // 2^8 = 256
        IO9 = 0x00000200, // 2^9 = 512
        IO10 = 0x00000400, // 2^10 = 1024
        IO11 = 0x00000800, // 2^11 = 2048
        IO12 = 0x00001000, // 2^12 = 4096
        IO13 = 0x00002000, // 2^13 = 8192
        IO14 = 0x00004000, // 2^14 = 16384
        IO15 = 0x00008000, // 2^15 = 32768
        IO16 = 0x00010000, // 2^16 = 65536
        IO17 = 0x00020000, // 2^17 = 131072
        IO18 = 0x00040000, // 2^18 = 262144
        IO19 = 0x00080000, // 2^19 = 524288
        IO20 = 0x00100000, // 2^20 = 1048576
        IO21 = 0x00200000, // 2^21 = 2097152
        IO22 = 0x00400000, // 2^22 = 4194304
        IO23 = 0x00800000, // 2^23 = 8388608
        IO24 = 0x01000000, // 2^24 = 16777216
        IO25 = 0x02000000, // 2^25 = 33554432
        IO26 = 0x04000000, // 2^26 = 67108864
        IO27 = 0x08000000, // 2^27 = 134217728
        IO28 = 0x10000000, // 2^28 = 268435456
        IO29 = 0x20000000, // 2^29 = 536870912
        IO30 = 0x40000000, // 2^30 = 1073741824
        IO31 = 0x80000000, // 2^31 = 2147483648(uint,超 int 范围,必须 uint 底层)
    }
}
